// ---- Database ------------------------------------------------------------------------------------------------------
{
  const root = path.join(contracts, 'db', 'postgresql');
  const capabilities = [
    ['auth', 'Sign-in & identity', 'egradx_auth_schema_history'],
    ['audit', 'Audit trail', 'egradx_audit_schema_history'],
    ['notification', 'Notifications', 'egradx_notification_schema_history'],
    ['events', 'Events', 'egradx_events_schema_history'],
  ];
  let body = 'Every table the SDK creates in your database, with its columns as its migrations leave them. Each library records its migrations in its own history table; [the database guide](/docs/guides/database) explains the order.\n';
  for (const [folder, title, history] of capabilities) {
    const files = readdirSync(path.join(root, folder)).filter((f) => f.endsWith('.sql')).sort((a, b) => parseInt(a.slice(1)) - parseInt(b.slice(1)));
    const tables = new Map();
    const ordered = [];
    for (const file of files) {
      const sql = readFileSync(path.join(root, folder, file), 'utf8').replace(/\r\n/g, '\n').replace(/--[^\n]*/g, '');
      for (const match of sql.matchAll(/CREATE TABLE(?: IF NOT EXISTS)?\s+(\w+)\s*\(([\s\S]*?)\n\)\s*;/gi)) {
        const columns = [];
        for (const raw of splitTopLevel(match[2])) {
          const line = raw.trim().replace(/\s+/g, ' ');
          if (!line || /^(CONSTRAINT|PRIMARY KEY|UNIQUE|FOREIGN KEY|CHECK)\b/i.test(line)) continue;
          const [name, ...rest] = line.split(' ');
          columns.push({ name, definition: rest.join(' '), since: file });
        }
        tables.set(match[1], { columns, since: file });
        ordered.push(match[1]);
      }
      for (const match of sql.matchAll(/ALTER TABLE\s+(\w+)\s+([\s\S]*?);/gi)) {
        const table = tables.get(match[1]);
        if (!table) continue;
        for (const clause of splitTopLevel(match[2])) {
          const add = /^\s*ADD COLUMN(?: IF NOT EXISTS)?\s+(\w+)\s+([\s\S]+)$/i.exec(clause);
          if (add) table.columns.push({ name: add[1], definition: add[2].trim().replace(/\s+/g, ' '), since: file });
          const drop = /^\s*DROP COLUMN(?: IF EXISTS)?\s+(\w+)/i.exec(clause);
          if (drop) table.columns = table.columns.filter((c) => c.name !== drop[1]);
          const rename = /^\s*RENAME COLUMN\s+(\w+)\s+TO\s+(\w+)/i.exec(clause);
          if (rename) table.columns = table.columns.map((c) => (c.name === rename[1] ? { ...c, name: rename[2], since: file } : c));
        }
      }
    }
    body += `\n## ${title}\n\nMigrations: ${files.map((f) => `\`${f}\``).join(', ')} — history table \`${history}\`.\n`;
    for (const name of ordered) {
      body += `\n### \`${name}\`\n\n| Column | Definition | Since |\n|---|---|---|\n`;
      for (const column of tables.get(name).columns) body += `| \`${column.name}\` | \`${column.definition.replace(/\|/g, '\\|')}\` | ${column.since.split('__')[0]} |\n`;
    }
  }
  written.push(page('database.mdx', { title: 'Database', description: "Every table and column the SDK creates in your PostgreSQL database — from the migrations in contracts/db." }, body));
}

/** Splits a column list on commas that are not inside parentheses. */
function splitTopLevel(textValue) {
  const parts = [];
  let depth = 0;
  let current = '';
  for (const char of textValue) {
    if (char === '(') depth++;
    if (char === ')') depth--;
    if (char === ',' && depth === 0) {
      parts.push(current);
      current = '';
    } else current += char;
  }
  if (current.trim()) parts.push(current);
  return parts;
}

