// ---- HTTP ----------------------------------------------------------------------------------------------------------
{
  const apis = [
    ['auth', 'Sign-in & identity', '/egradx/auth/**: sign-in, sessions, accounts, organizations, users, roles, invitations, profiles.'],
    ['audit', 'Audit trail', '/egradx/audit/**: records, history, export, the action catalog.'],
    ['notification', 'Notifications', '/egradx/notifications/**: the inbox and its stream, preferences, and the administration of channels, templates and deliveries.'],
  ];
  for (const [name, title, scope] of apis) {
    const spec = parse(read(`openapi/${name}.yaml`));
    const schemas = spec.components?.schemas ?? {};
    const tags = new Map();
    for (const [route, item] of Object.entries(spec.paths ?? {})) {
      for (const method of ['get', 'post', 'put', 'patch', 'delete']) {
        const operation = item[method];
        if (!operation) continue;
        const tag = operation.tags?.[0] ?? 'Other';
        if (!tags.has(tag)) tags.set(tag, []);
        tags.get(tag).push({ route, method, operation });
      }
    }
    const tagInfo = new Map((spec.tags ?? []).map((t) => [t.name, t.description]));
    let body = `${text(scope)} The same endpoints in Java, Node and Python, mounted under your application's base path; every refusal is the [error envelope](/docs/reference/errors). Generated from \`contracts/openapi/${name}.yaml\`.\n`;
    for (const [tag, operations] of tags) { // in the order the contract first uses them
      body += `\n## ${text(/^[a-z0-9-]+$/.test(tag) ? humanize(tag) : tag)}\n\n${tagInfo.get(tag) ? `${text(tagInfo.get(tag))}\n\n` : ''}`;
      for (const { route, method, operation } of operations.sort((a, b) => a.route.localeCompare(b.route))) {
        body += `### ${text(operation.summary ?? humanize(operation.operationId ?? `${method} ${route}`))}\n\n\`\`\`http\n${method.toUpperCase()} ${route}\n\`\`\`\n\n`;
        if (operation.description) body += `${text(operation.description)}\n\n`;
        const parameters = (operation.parameters ?? []).flatMap((p) => expandParameter(p, schemas));
        if (parameters.length) {
          body += '| Parameter | In | Type | Required |\n|---|---|---|---|\n';
          for (const p of parameters) body += `| \`${p.name}\` | ${p.in} | ${p.type} | ${p.required ? 'yes' : ''} |\n`;
          body += '\n';
        }
        const requestSchema = firstSchema(operation.requestBody?.content);
        if (requestSchema) body += `**Body:** ${schemaLink(requestSchema)}\n\n`;
        const responses = Object.entries(operation.responses ?? {});
        if (responses.length) {
          body += '| Answer | Body |\n|---|---|\n';
          for (const [status, response] of responses) body += `| ${status} ${text(response.description ?? '')} | ${schemaLink(firstSchema(response.content))} |\n`;
          body += '\n';
        }
      }
    }
    body += '\n## Schemas\n';
    for (const [schemaName, schema] of Object.entries(schemas).sort(([a], [b]) => a.localeCompare(b))) {
      body += `\n### ${schemaName}\n\n`;
      const properties = Object.entries(schema.properties ?? {});
      if (!properties.length) {
        body += `${schema.enum ? `One of ${schema.enum.map((v) => `\`${v}\``).join(', ')}.` : 'An object.'}\n`;
        continue;
      }
      const required = new Set(schema.required ?? []);
      body += '| Field | Type | Required |\n|---|---|---|\n';
      for (const [field, property] of properties) body += `| \`${field}\` | ${typeOf(property)} | ${required.has(field) ? 'yes' : ''} |\n`;
    }
    written.push(page(`http/${name}.mdx`, { title: `HTTP: ${title}`, description: `Every endpoint of ${scope.split(':')[0]}, with its parameters, body and answers.` }, body));
  }
}

function humanize(value) {
  const words = String(value).replace(/^egradx-/, '').replace(/-controller$/, '').replace(/([a-z])([A-Z])/g, '$1 $2').replace(/[-_]/g, ' ').toLowerCase();
  return words.charAt(0).toUpperCase() + words.slice(1);
}

function refName(ref) {
  return ref.split('/').pop();
}

function typeOf(schema) {
  if (!schema) return '';
  if (schema.$ref) return `[${refName(schema.$ref)}](#${refName(schema.$ref).toLowerCase()})`;
  if (schema.anyOf || schema.oneOf) return (schema.anyOf ?? schema.oneOf).map(typeOf).filter((t) => t && t !== 'null').join(' or ') + ((schema.anyOf ?? schema.oneOf).some((s) => s.type === 'null' || (Array.isArray(s.types) && s.types.includes('null'))) ? ' (nullable)' : '');
  const type = Array.isArray(schema.type) ? schema.type.filter((t) => t !== 'null').join(' or ') : schema.type;
  if (type === 'array') return `array of ${typeOf(schema.items)}`;
  if (schema.enum) return schema.enum.map((v) => `\`${v}\``).join(', ');
  return `${type ?? 'object'}${schema.format ? ` (${schema.format})` : ''}`;
}

function schemaLink(schema) {
  return schema ? typeOf(schema) : '—';
}

function firstSchema(content) {
  if (!content) return undefined;
  const first = Object.values(content)[0];
  return first?.schema;
}

/** springdoc renders a query object as one parameter: show its fields, which are what goes on the wire. */
function expandParameter(parameter, schemas) {
  const schema = parameter.schema?.$ref ? schemas[refName(parameter.schema.$ref)] : parameter.schema;
  if (parameter.in === 'query' && schema?.properties && parameter.schema?.$ref) {
    return Object.entries(schema.properties).map(([name, property]) => ({ name, in: 'query', type: typeOf(property), required: false }));
  }
  return [{ name: parameter.name, in: parameter.in, type: typeOf(parameter.schema), required: parameter.required }];
}

