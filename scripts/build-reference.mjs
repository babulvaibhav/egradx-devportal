// Writes the generated reference pages (content/docs/reference/**) from the contracts in sources/ and the catalogs
// recorded from the example applications (content/results/catalog.json). A reference that drifts from the code is
// worse than none, so these pages are never edited by hand: `npm run build` writes them first, and they are not
// committed (.gitignore). Fails, naming what is missing, when a source and the portal's own data disagree.
//
//   node scripts/build-reference.mjs
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const app = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const contracts = path.join(app, 'sources', 'contracts');
const out = path.join(app, 'content', 'docs', 'reference');
const read = (relative) => readFileSync(path.join(contracts, relative), 'utf8').replace(/\r\n/g, '\n');
const json = (relative) => JSON.parse(read(relative));

const GENERATED = '{/* Generated by scripts/build-reference.mjs from the contracts — do not edit: edit the source and rebuild. */}';

/** Text safe in MDX prose and table cells: no JSX, no table breaks. Code spans are left as they are. */
function text(value) {
  return String(value ?? '')
    .split(/(`[^`]*`)/)
    .map((part, i) => (i % 2 === 1 ? part : part.replace(/[{}]/g, (c) => `\\${c}`).replace(/</g, '&lt;').replace(/>/g, '&gt;')))
    .join('')
    .replace(/\|/g, '\\|')
    .replace(/\n+/g, ' ')
    .trim();
}

function page(file, frontmatter, body) {
  const target = path.join(out, file);
  mkdirSync(path.dirname(target), { recursive: true });
  const head = Object.entries(frontmatter).map(([key, value]) => `${key}: ${JSON.stringify(value)}`).join('\n');
  writeFileSync(target, `---\n${head}\n---\n\n${GENERATED}\n\n${body.trim()}\n`);
  return file;
}

