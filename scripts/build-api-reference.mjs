// Writes the language API references from the SDK's own source, in the monorepo (it needs sdks/): Node and web with
// TypeDoc, Python with griffe, Java with javadoc. Unlike the contract pages, these are committed — a repository holding
// only the portal can't make them — so run this after an SDK change and commit content/docs/reference/{node,web,python}
// and public/reference/java.
//
//   node scripts/build-api-reference.mjs [node] [web] [python] [java]
//
// Needs: tools/reference installed (cd tools/reference && npm install); the SDK's JavaScript packages installed (pnpm
// install at the monorepo root); uv (the monorepo's .tools/uv, or on the PATH); Maven for java.
import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import GithubSlugger from 'github-slugger';

const app = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const monorepo = path.resolve(app, '..', '..');
const windows = process.platform === 'win32';
const tools = path.join(app, 'tools', 'reference');
const wanted = process.argv.slice(2);
const want = (name) => wanted.length === 0 || wanted.includes(name);

if (!existsSync(path.join(monorepo, 'sdks'))) {
  console.error('Run this in the monorepo (egradx-v1-workspace): it reads the SDK source in sdks/.');
  process.exit(1);
}

function run(command, args, options = {}) {
  const result = spawnSync(command, args, { encoding: 'utf8', shell: windows, ...options });
  if (result.status !== 0) {
    throw new Error(`${command} ${args.join(' ')} failed:\n${(result.stdout ?? '') + (result.stderr ?? '')}`.slice(-6000));
  }
  return result.stdout;
}

/** The first paragraph of Markdown that is prose, for a page's description. */
function firstParagraph(markdown) {
  const paragraph = markdown.split(/\n\s*\n/).map((p) => p.trim()).find((p) => p && !p.startsWith('#') && !p.startsWith('|') && !p.startsWith('```') && !p.startsWith('>') && !p.startsWith('-'));
  return (paragraph ?? '').replace(/\s+/g, ' ').replace(/[`*_[\]]/g, '').replace(/\(([^)]*)\)/g, '').slice(0, 200);
}

/** Front matter, and links into the SDK's internal docs (TypeDoc's _media) turned into plain text. */
function finish(markdown, title) {
  const body = markdown
    .replace(/^# .*\n+/, '')
    .replace(/\[([^\]]+)\]\((?:\.\.\/)*_media\/[^)]*\)/g, '$1')
    .replace(/\]\(@babulvaibhav\/(egradx-[a-z-]+)\.md/g, ']($1.md')
    .replace(/\]\(\.\.\/@babulvaibhav\/(egradx-[a-z-]+)\.md/g, ']($1.md');
  return `---\ntitle: ${JSON.stringify(title)}\ndescription: ${JSON.stringify(firstParagraph(body) || `The API of ${title}.`)}\n---\n\n<!-- Generated by scripts/build-api-reference.mjs from the SDK's source: do not edit. -->\n\n${body.trim()}\n`;
}

function typedoc(packages, folder, title) {
  const scratch = path.join(tools, '.out', folder);
  rmSync(scratch, { recursive: true, force: true });
  const options = path.join(scratch, 'typedoc.json');
  mkdirSync(scratch, { recursive: true });
  writeFileSync(options, JSON.stringify({
    entryPointStrategy: 'packages',
    entryPoints: packages.map((p) => p.split(path.sep).join('/')),
    packageOptions: { entryPoints: ['src/index.ts*'], skipErrorChecking: true, excludePrivate: true, excludeInternal: true, excludeExternals: true },
    plugin: ['typedoc-plugin-markdown'],
    out: path.join(scratch, 'out'),
    readme: 'none',
    skipErrorChecking: true,
    disableSources: true,
    outputFileStrategy: 'modules',
    hidePageHeader: true,
    hideBreadcrumbs: true,
    parametersFormat: 'table',
    interfacePropertiesFormat: 'table',
    classPropertiesFormat: 'table',
    typeDeclarationFormat: 'table',
    enumMembersFormat: 'table',
    useCodeBlocks: true,
    validation: { notExported: false, invalidLink: false, rewrittenLink: false },
  }, null, 2));
  run(path.join(tools, 'node_modules', '.bin', windows ? 'typedoc.cmd' : 'typedoc'), ['--options', options, '--logLevel', 'Warn'], { cwd: tools });
  const generated = path.join(scratch, 'out', '@babulvaibhav');
  const target = path.join(app, 'content', 'docs', 'reference', folder);
  rmSync(target, { recursive: true, force: true });
  mkdirSync(target, { recursive: true });
  const pages = [];
  // A package is one file, or a folder (when it exports namespaces) whose README.md is its page. The namespaces —
  // the client's generated OpenAPI types — repeat the HTTP reference, so links to them become plain text.
  const entries = readdirSync(generated, { withFileTypes: true })
    .map((entry) => (entry.isDirectory() ? [entry.name, path.join(generated, entry.name, 'README.md')] : [entry.name.replace(/\.md$/, ''), path.join(generated, entry.name)]))
    .filter(([, file]) => file.endsWith('.md') && existsSync(file))
    .sort(([a], [b]) => a.localeCompare(b));
  for (const [name, file] of entries) {
    const markdown = readFileSync(file, 'utf8').replace(/\[([^\]]+)\]\((?:\.\/)?namespaces\/[^)]*\)/g, '$1');
    writeFileSync(path.join(target, `${name}.md`), finish(markdown, `@babulvaibhav/${name}`));
    pages.push(name);
  }
  writeFileSync(path.join(target, 'meta.json'), `${JSON.stringify({ title, pages: ['index', ...pages] }, null, 2)}\n`);
  return pages;
}

/** Text for MDX prose and table cells: braces and angle brackets escaped outside code spans. */
function mdxText(value) {
  return String(value ?? '')
    .split(/(`[^`]*`)/)
    .map((part, i) => (i % 2 === 1 ? part : part.replace(/[{}]/g, (c) => `\\${c}`).replace(/</g, '&lt;').replace(/>/g, '&gt;')))
    .join('');
}

function indexPage(folder, title, description, rows) {
  const lines = rows.map(([page, what]) => `| [\`${page.startsWith('egradx') ? `@babulvaibhav/${page}` : page}\`](/docs/reference/${folder}/${page}) | ${mdxText(what)} |`);
  writeFileSync(
    path.join(app, 'content', 'docs', 'reference', folder, 'index.mdx'),
    `---\ntitle: ${JSON.stringify(title)}\ndescription: ${JSON.stringify(description.replace(/`/g, ''))}\n---\n\n{/* Generated by scripts/build-api-reference.mjs from the SDK's source: do not edit. */}\n\n${mdxText(description)} Each page starts with the package's own overview, then every export.\n\n| Package | What it is |\n|---|---|\n${lines.join('\n')}\n`,
  );
}

/**
 * Links in a folder's generated pages, made to work on the site: `x.md` and `x/README.md` become the page's path, an
 * anchor stays only if the target page has that heading (the ids Fumadocs gives headings, by github-slugger), and a
 * link into the SDK's own docs or files becomes its text — except the two that have a page here.
 */
function fixLinks(folder) {
  const dir = path.join(app, 'content', 'docs', 'reference', folder);
  const pages = readdirSync(dir).filter((f) => f.endsWith('.md')).map((f) => f.replace(/\.md$/, ''));
  const plain = (heading) => heading.replace(/\[([^\]]*)\]\([^)]*\)/g, '$1').replace(/[`*\\]/g, '').trim();
  const slugs = new Map(pages.map((page) => {
    const slugger = new GithubSlugger();
    const text = readFileSync(path.join(dir, `${page}.md`), 'utf8').replace(/```[\s\S]*?```/g, '');
    return [page, new Set([...text.matchAll(/^#{1,6} (.+)$/gm)].map((m) => slugger.slug(plain(m[1]))))];
  }));
  const elsewhere = [[/(^|\/)docs\/observability\/guide\.md$/, '/docs/guides/observability'], [/(^|\/)contracts\/events\/asyncapi\.yaml$/, '/docs/reference/events']];
  for (const page of pages) {
    const file = path.join(dir, `${page}.md`);
    const markdown = readFileSync(file, 'utf8').replace(/(?<!!)\[([^\]]+)\]\(([^)\s]+)\)/g, (whole, label, href) => {
      if (/^(https?:|mailto:|\/)/.test(href)) return whole;
      const [target, anchor] = href.split('#');
      if (!target) return anchor && slugs.get(page).has(anchor) ? whole : label;
      const known = elsewhere.find(([pattern]) => pattern.test(target));
      if (known) return `[${label}](${known[1]})`;
      const name = target.replace(/^(\.\.?\/)+/, '').replace(/\/README\.md$/, '').replace(/\.md$/, '');
      if (!pages.includes(name)) return label;
      return `[${label}](/docs/reference/${folder}/${name}${anchor && slugs.get(name).has(anchor) ? `#${anchor}` : ''})`;
    });
    writeFileSync(file, markdown);
  }
}

function describe(packageDir) {
  return JSON.parse(readFileSync(path.join(packageDir, 'package.json'), 'utf8')).description ?? '';
}

if (want('node')) {
  const root = path.join(monorepo, 'sdks', 'node', 'packages');
  const order = ['sdk', 'core', 'auth', 'audit', 'notification', 'events', 'observability', 'express', 'security', 'migrations', 'tls-provider', 'audit-auth', 'notification-auth'];
  const packages = order.filter((name) => existsSync(path.join(root, name, 'src', 'index.ts'))).map((name) => path.join(root, name));
  const pages = typedoc(packages, 'node', 'Node');
  fixLinks('node');
  indexPage('node', 'Node API', 'The Node SDK, package by package. Most applications need only @babulvaibhav/egradx-sdk, which re-exports the others it wires, and @babulvaibhav/egradx-events when they publish events.',
    pages.map((page) => [page, describe(path.join(root, page.replace(/^egradx-/, ''))).replace(/\|/g, '\\|')]));
  console.log(`node: ${pages.length} packages`);
}

if (want('web')) {
  const root = path.join(monorepo, 'sdks', 'web', 'packages');
  const packages = ['client', 'react', 'next'].map((name) => path.join(root, name));
  const pages = typedoc(packages, 'web', 'Web');
  fixLinks('web');
  indexPage('web', 'Web API', 'The browser packages: the client, the React hooks and the Next.js backend-for-frontend. The copy-in screens are source you own, served at `/r/<item>.json`.',
    pages.map((page) => [page, describe(path.join(root, page.replace(/^egradx-/, ''))).replace(/\|/g, '\\|')]));
  console.log(`web: ${pages.length} packages`);
}

if (want('python')) {
  const workspaceUv = path.join(monorepo, '.tools', 'uv', windows ? 'Scripts/uv.exe' : 'bin/uv');
  const uv = existsSync(workspaceUv) ? workspaceUv : 'uv';
  const target = path.join(app, 'content', 'docs', 'reference', 'python');
  rmSync(target, { recursive: true, force: true });
  mkdirSync(target, { recursive: true });
  const env = { ...process.env, ...(existsSync(workspaceUv) ? { UV_CACHE_DIR: path.join(monorepo, '.cache', 'uv') } : {}), PYTHONUTF8: '1' };
  console.log(run(uv, ['run', '--quiet', '--with', 'griffe>=1.5', 'python', path.join(tools, 'python_api.py'), target], { cwd: monorepo, env }).trim());
  fixLinks('python');
}

if (want('java')) {
  const reactor = path.join(monorepo, 'sdks', 'java');
  run('mvn', ['-B', '-q', '-f', path.join(reactor, 'pom.xml'), 'clean', 'install', '-DskipTests']);
  run('mvn', ['-B', '-q', '-f', path.join(reactor, 'pom.xml'), 'javadoc:aggregate', '-Ddoclint=none', '-Dmaven.javadoc.failOnError=false', '-Dmaven.javadoc.failOnWarnings=false']);
  const site = path.join(reactor, 'target', 'reports', 'apidocs');
  const generated = existsSync(site) ? site : path.join(reactor, 'target', 'site', 'apidocs');
  const target = path.join(app, 'public', 'reference', 'java');
  rmSync(target, { recursive: true, force: true });
  cpSync(generated, target, { recursive: true });
  console.log(`java: javadoc copied into public/reference/java`);
  javaConfiguration(reactor);
}

/**
 * Every egradx.* key the Java modules declare, from the metadata spring-boot-configuration-processor writes, into
 * data/java-configuration.json — which scripts/build-reference.mjs turns into the configuration page.
 */
function javaConfiguration(reactor) {
  // Keys read with @Value or @ConditionalOnProperty alone, which the processor can't see.
  const extra = [
    { name: 'egradx.security.crypto.keystorePath', type: 'java.lang.String', module: 'egradx-tls-provider', description: 'The folder holding the signing and encryption keys; created with them on the first start. Every instance shares it. Written exactly so: it is read as written.' },
    { name: 'egradx.security.crypto.passphrase', type: 'java.lang.String', module: 'egradx-tls-provider', description: 'Encrypts the private keys in the keys folder. Required; keep it stable and secret.' },
    { name: 'egradx.service.token.enabled', type: 'java.lang.Boolean', module: 'egradx-web-security', defaultValue: false, description: 'Creates the EgradxServiceTokenManager, which gets client-credentials tokens from an outside OAuth server (egradx.security.client.*).' },
  ];
  // Declared but never registered: setting them does nothing (restructure log, finding 17).
  const ignored = /EgradxSdkProperties/;
  const properties = [];
  for (const name of readdirSync(reactor).sort()) {
    const file = path.join(reactor, name, 'target', 'classes', 'META-INF', 'spring-configuration-metadata.json');
    if (!existsSync(file)) continue;
    for (const p of JSON.parse(readFileSync(file, 'utf8')).properties ?? []) {
      if (!p.name.startsWith('egradx.') || ignored.test(p.sourceType ?? '')) continue;
      properties.push({ name: p.name, type: p.type, module: name, ...(p.defaultValue !== undefined ? { defaultValue: p.defaultValue } : {}), ...(p.description ? { description: p.description } : {}), ...(p.deprecated ? { deprecated: true } : {}) });
    }
  }
  const known = new Set(properties.map((p) => p.name));
  properties.push(...extra.filter((p) => !known.has(p.name)));
  properties.sort((a, b) => a.name.localeCompare(b.name));
  writeFileSync(path.join(app, 'data', 'java-configuration.json'), `${JSON.stringify({ note: 'Generated by scripts/build-api-reference.mjs java from the SDK modules\' configuration metadata: do not edit.', properties }, null, 2)}\n`);
  console.log(`java: ${properties.length} configuration keys in data/java-configuration.json`);
}
